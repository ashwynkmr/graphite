// Builds the lowercase-g icons (FB-18): Newsreader's serif "g" on the spiral-notebook page,
// with either a pencil or a fountain pen resting on it. The glyph is converted to a path so
// the SVG needs no font. Newsreader is SIL OFL, which allows this use.
// Usage: node tools/icons/build-g.mjs   → tools/icons/g-pencil.svg, tools/icons/g-pen.svg
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const fontFile = new URL('../../node_modules/@fontsource/newsreader/files/newsreader-latin-400-normal.woff', import.meta.url);
const bytes = readFileSync(fontFile);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));

/** SVG path data from opentype.js commands, written out explicitly so every contour closes. */
function toD(commands) {
  const n = (v) => v.toFixed(2);
  return commands
    .map((c) => {
      if (c.type === 'M' || c.type === 'L') return `${c.type}${n(c.x)} ${n(c.y)}`;
      if (c.type === 'Q') return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
      if (c.type === 'C') return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
      return 'Z';
    })
    .join('');
}

// Fit the glyph into a box on the page (right of the spiral and margin).
const BOX = { x1: 190, y1: 116, x2: 372, y2: 412 };
function glyphPath() {
  const probe = font.getPath('g', 0, 0, 100);
  const bb = probe.getBoundingBox();
  const scale = Math.min((BOX.x2 - BOX.x1) / (bb.x2 - bb.x1), (BOX.y2 - BOX.y1) / (bb.y2 - bb.y1));
  const size = 100 * scale;
  const w = (bb.x2 - bb.x1) * scale;
  const h = (bb.y2 - bb.y1) * scale;
  const x = BOX.x1 + (BOX.x2 - BOX.x1 - w) / 2 - bb.x1 * scale;
  const y = BOX.y1 + (BOX.y2 - BOX.y1 - h) / 2 - bb.y1 * scale;
  const path = font.getPath('g', x, y, size);
  return { d: toD(path.commands), box: path.getBoundingBox() };
}

