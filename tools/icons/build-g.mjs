function icon({ instrument, ink, tip, angle, scale, label }) {
  const g = glyphPath();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- FB-18 (${label}): Newsreader lowercase g on a spiral-notebook page. Generated by tools/icons/build-g.mjs -->${page}
  <path d="${g.d}" fill="${ink}"/>
  <g transform="translate(${tip[0] + 6} ${tip[1] + 8}) rotate(${angle}) scale(${scale})" opacity="0.18">${instrument.replace(/fill="#[0-9a-f]+"/gi, 'fill="#000"').replace(/stroke="#[0-9a-f]+"/gi, 'stroke="#000"')}</g>
  <g transform="translate(${tip[0]} ${tip[1]}) rotate(${angle}) scale(${scale})">${instrument}
  </g>
</svg>
`;
}

// The point rests at the end of the g's ear (top right), as if it just finished the letter;
// the body lies down to the right so the whole instrument stays in view.
const { box } = glyphPath();
const tip = [Math.round(box.x2 + 2), Math.round(box.y1 + 18)];
const pose = { tip, angle: 58, scale: 0.72 };
writeFileSync(new URL('./g-pencil.svg', import.meta.url), icon({ instrument: PENCIL, ink: '#2a2a2d', ...pose, label: 'pencil' }));
writeFileSync(new URL('./g-pen.svg', import.meta.url), icon({ instrument: PEN, ink: '#2c4a7c', ...pose, label: 'fountain pen' }));
console.log('wrote tools/icons/g-pencil.svg and g-pen.svg; tip at', tip);
