// Builds tools/icons/cursive.svg: one continuous pencil bent into a cursive G (FB-17),
// on the spiral-notebook page. The eraser and sharpened point are rotated to the curve's
// direction at each end, which is why this is generated rather than hand-drawn.
// Usage: node tools/icons/build-cursive.mjs
import { writeFileSync } from 'node:fs';

// The G as cubic Bézier segments [c1, c2, end], starting at START. Start = eraser end, last end = point.
const START = [384, 132];
const SEGMENTS = [
  [[364, 104], [300, 98], [252, 116]],
  [[194, 138], [164, 200], [170, 264]],
  [[176, 332], [232, 372], [292, 368]],
  [[350, 364], [384, 324], [382, 276]],
  [[380, 248], [358, 238], [334, 246]],
];
const W = 30; // pencil width
const SLANT = -10; // degrees of italic slant, for a script feel

const path = `M${START.join(' ')}` + SEGMENTS.map(([a, b, c]) => `C${a.join(' ')} ${b.join(' ')} ${c.join(' ')}`).join('');
const deg = (dx, dy) => (Math.atan2(dy, dx) * 180) / Math.PI;

// Direction pointing back out of the start (for the eraser) and forward out of the end (for the point).
const [s1] = SEGMENTS[0];
const eraserAngle = deg(START[0] - s1[0], START[1] - s1[1]);
const last = SEGMENTS[SEGMENTS.length - 1];
const endPt = last[2];
const tipAngle = deg(endPt[0] - last[1][0], endPt[1] - last[1][1]);
const h = W / 2;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- FB-17: one continuous amber pencil bent into a cursive G, on a ruled spiral-notebook page over ink blue.
       Generated by tools/icons/build-cursive.mjs -->
  <rect width="512" height="512" fill="#2c4a7c"/>
  <rect x="112" y="80" width="336" height="368" rx="18" fill="#1f365d"/>
  <rect x="104" y="72" width="336" height="368" rx="18" fill="#f6f1e7"/>
  <g stroke="#9fb1cf" stroke-opacity="0.6" stroke-width="3">
    <path d="M148 150H420M148 194H420M148 238H420M148 282H420M148 326H420M148 370H420M148 414H420"/>
  </g>
  <path d="M172 72V440" stroke="#e0a24a" stroke-width="3" stroke-opacity="0.75"/>
  <g fill="#2c4a7c">${[112, 164, 216, 268, 320, 372].map((y) => `<circle cx="128" cy="${y}" r="8"/>`).join('')}</g>
  <g fill="none" stroke="#d3d8e0" stroke-width="7" stroke-linecap="round">${[112, 164, 216, 268, 320, 372]
    .map((y) => `<path d="M128 ${y}C112 ${y - 12} 92 ${y - 10} 86 ${y}C92 ${y + 10} 112 ${y + 12} 128 ${y}"/>`)
    .join('')}</g>
  <g transform="translate(276 250) skewX(${SLANT}) translate(-276 -250)">
  <!-- pencil body: dark edge, amber face, light facet -->
  <path d="${path}" fill="none" stroke="#b9831d" stroke-width="${W}"/>
  <path d="${path}" fill="none" stroke="#e9b949" stroke-width="${W - 8}"/>
  <path d="${path}" fill="none" stroke="#f4d27a" stroke-width="4"/>
  <!-- ferrule and eraser at the start -->
  <g transform="translate(${START.join(' ')}) rotate(${eraserAngle.toFixed(1)})">
    <rect x="-1" y="${-h}" width="12" height="${W}" fill="#b9c0ca"/>
    <path d="M3 ${-h}V${h}M7 ${-h}V${h}" stroke="#8e96a2" stroke-width="1.5"/>
    <path d="M11 ${-h}H22A${h - 2} ${h} 0 0 1 22 ${h}H11Z" fill="#e58f8f"/>
  </g>
  <!-- sharpened wood and graphite point at the end -->
  <g transform="translate(${endPt.join(' ')}) rotate(${tipAngle.toFixed(1)})">
    <path d="M-1 ${-h}V${h}L36 0Z" fill="#f0d9b0"/>
    <path d="M25 ${-h * (11 / 37)}V${h * (11 / 37)}L36 0Z" fill="#2a2a2d"/>
  </g>
  </g>
</svg>
`;
writeFileSync(new URL('./cursive.svg', import.meta.url), svg);
console.log('wrote tools/icons/cursive.svg');
